import "dotenv/config";
import { AsyncLocalStorage } from "node:async_hooks";
import { randomBytes, randomUUID } from "node:crypto";
import { afterAll, beforeAll, describe, expect, it, vi } from "vitest";
import { hashPassword, hashToken } from "@/lib/password";
import { addDays, todayInTimezone } from "@/lib/dates";

// This suite deliberately uses real PostgreSQL and real route handlers. Only
// Next.js request cookie storage is replaced, so requests can run without a web
// server. RUN_DB_TESTS=true is an explicit opt-in to creating fixture accounts.
// Cleanup can delete only exact IDs/email digests generated by this test run.
const runId = randomUUID();
const testPassword = `Qa ${randomBytes(24).toString("hex")}!`;
const testUsers: string[] = [];
const testEmails: string[] = [];
let db: typeof import("@/lib/db").db;
type CookieJar = {
  values: Map<string, string>;
  options: Map<string, Record<string, unknown>>;
  get: (name: string) => { value: string } | undefined;
  set: (name: string, value: string, options?: Record<string, unknown>) => void;
};
function newJar(): CookieJar {
  const values = new Map<string, string>();
  const options = new Map<string, Record<string, unknown>>();
  return {
    values,
    options,
    get: (name) => (values.has(name) ? { value: values.get(name)! } : undefined),
    set: (name, value, settings = {}) => {
      values.set(name, value);
      options.set(name, settings);
    },
  };
}
const cookieStorage = new AsyncLocalStorage<CookieJar>();
const primaryJar = newJar();
const otherJar = newJar();
const initialJar = newJar();
let primaryId: string;
let primaryEmail: string;
let otherId: string;
let initialId: string;
let initialEmail: string;
let throttleEmail: string;
type Handler = (
  request: Request,
  context: { params: Promise<{ id: string }> },
) => Promise<Response>;
let routes: {
  login: typeof import("@/app/api/auth/login/route");
  logout: typeof import("@/app/api/auth/logout/route");
  password: typeof import("@/app/api/auth/password/route");
  entries: typeof import("@/app/api/entries/route");
  entry: typeof import("@/app/api/entries/[id]/route");
  workspace: typeof import("@/app/api/workspace/route");
  habits: typeof import("@/app/api/habit-logs/route");
  study: typeof import("@/app/api/study-sessions/route");
  studyItem: typeof import("@/app/api/study-sessions/[id]/route");
  transactions: typeof import("@/app/api/transactions/route");
  transaction: typeof import("@/app/api/transactions/[id]/route");
  savings: typeof import("@/app/api/savings/route");
  saving: typeof import("@/app/api/savings/[id]/route");
  budgets: typeof import("@/app/api/budgets/route");
  budget: typeof import("@/app/api/budgets/[id]/route");
  planner: typeof import("@/app/api/daily-plans/route");
};
function invoke(
  handler: Handler,
  method: string,
  body?: unknown,
  jar = primaryJar,
  id = "",
  origin = new URL(process.env.APP_URL!).origin,
) {
  const request = new Request(`${process.env.APP_URL}/api/integration`, {
    method,
    headers: { origin, "content-type": "application/json", "x-real-ip": "192.0.2.24" },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
  return cookieStorage.run(jar, () => handler(request, { params: Promise.resolve({ id }) }));
}
async function data(response: Response): Promise<Record<string, unknown>> {
  const result = (await response.json()) as { data?: Record<string, unknown>; error?: string };
  expect(response.status, result.error).toBeLessThan(400);
  return result.data!;
}
async function create(kind: string, values: Record<string, unknown> = {}, jar = primaryJar) {
  return data(
    await invoke(routes.entries.POST, "POST", { kind, title: `QA ${kind}`, ...values }, jar),
  );
}

describe.runIf(process.env.RUN_DB_TESTS === "true")("PostgreSQL API integration", () => {
  beforeAll(async () => {
    if (!process.env.APP_URL || !process.env.SESSION_SECRET || !process.env.DATABASE_URL)
      throw new Error("Integration tests require APP_URL, SESSION_SECRET and DATABASE_URL");
    db = (await import("@/lib/db")).db;
    vi.doMock("next/headers", () => ({
      cookies: async () => {
        const jar = cookieStorage.getStore();
        if (!jar) throw new Error("Missing test request cookie context");
        return jar;
      },
    }));
    const [
      login,
      logout,
      password,
      entries,
      entry,
      workspace,
      habits,
      study,
      studyItem,
      transactions,
      transaction,
      savings,
      saving,
      budgets,
      budget,
      planner,
    ] = await Promise.all([
      import("@/app/api/auth/login/route"),
      import("@/app/api/auth/logout/route"),
      import("@/app/api/auth/password/route"),
      import("@/app/api/entries/route"),
      import("@/app/api/entries/[id]/route"),
      import("@/app/api/workspace/route"),
      import("@/app/api/habit-logs/route"),
      import("@/app/api/study-sessions/route"),
      import("@/app/api/study-sessions/[id]/route"),
      import("@/app/api/transactions/route"),
      import("@/app/api/transactions/[id]/route"),
      import("@/app/api/savings/route"),
      import("@/app/api/savings/[id]/route"),
      import("@/app/api/budgets/route"),
      import("@/app/api/budgets/[id]/route"),
      import("@/app/api/daily-plans/route"),
    ]);
    routes = {
      login,
      logout,
      password,
      entries,
      entry,
      workspace,
      habits,
      study,
      studyItem,
      transactions,
      transaction,
      savings,
      saving,
      budgets,
      budget,
      planner,
    };
    const passwordHash = await hashPassword(testPassword);
    for (const role of ["primary", "other", "initial", "throttle"]) {
      const email = `qa-integration-${runId}-${role}@example.invalid`;
      testEmails.push(email);
      const user = await db.user.create({
        data: {
          email,
          name: "Integration fixture",
          passwordHash,
          mustChangePassword: role === "initial",
        },
      });
      testUsers.push(user.id);
      if (role === "primary") {
        primaryId = user.id;
        primaryEmail = email;
      }
      if (role === "other") otherId = user.id;
      if (role === "initial") {
        initialId = user.id;
        initialEmail = email;
      }
      if (role === "throttle") throttleEmail = email;
    }
    for (const [email, jar] of [
      [primaryEmail, primaryJar],
      [testEmails[1], otherJar],
      [initialEmail, initialJar],
    ] as const)
      expect(
        (await invoke(routes.login.POST, "POST", { email, password: testPassword }, jar)).status,
      ).toBe(200);
  }, 60000);

  afterAll(async () => {
    try {
      if (testUsers.length) await db.user.deleteMany({ where: { id: { in: testUsers } } });
      if (testEmails.length)
        await db.loginAudit.deleteMany({ where: { emailHash: { in: testEmails.map(hashToken) } } });
    } finally {
      await db?.$disconnect();
      vi.doUnmock("next/headers");
    }
  }, 30000);

  it("authenticates securely and blocks unauthenticated, CSRF and initial-password edits", async () => {
    const jarOptions = primaryJar.options.get("life_planning_session");
    expect(jarOptions).toMatchObject({ httpOnly: true, sameSite: "lax", path: "/" });
    expect((await invoke(routes.workspace.GET, "GET", undefined, newJar())).status).toBe(401);
    expect(
      (
        await invoke(
          routes.entries.POST,
          "POST",
          { kind: "goal", title: "Blocked" },
          primaryJar,
          "",
          "https://foreign.example",
        )
      ).status,
    ).toBe(403);
    expect(
      (await invoke(routes.entries.POST, "POST", { kind: "goal", title: "Blocked" }, initialJar))
        .status,
    ).toBe(403);
    const workspace = await data(await invoke(routes.workspace.GET, "GET"));
    expect(workspace.user).not.toHaveProperty("passwordHash");
    expect(
      await db.loginAudit.count({
        where: { emailHash: hashToken(primaryEmail), successful: true },
      }),
    ).toBe(1);
  });

  it("enforces entry ownership for reads, edits, deletes and relations", async () => {
    const foreign = await create("goal", {}, otherJar);
    const foreignId = String(foreign.id);
    expect((await invoke(routes.entry.GET, "GET", undefined, primaryJar, foreignId)).status).toBe(
      404,
    );
    expect(
      (
        await invoke(
          routes.entry.PATCH,
          "PATCH",
          { title: "Attempted overwrite" },
          primaryJar,
          foreignId,
        )
      ).status,
    ).toBe(404);
    expect(
      (await invoke(routes.entry.DELETE, "DELETE", undefined, primaryJar, foreignId)).status,
    ).toBe(404);
    expect(
      (
        await invoke(routes.entries.POST, "POST", {
          kind: "task",
          title: "Cross owner",
          goalId: foreignId,
        })
      ).status,
    ).toBe(400);
    const workspace = await data(await invoke(routes.workspace.GET, "GET"));
    expect(
      (workspace.entries as Record<string, unknown>[]).some((entry) => entry.id === foreignId),
    ).toBe(false);
    expect((await db.entry.findUnique({ where: { id: foreignId } }))?.userId).toBe(otherId);
  });

  it("preserves parent and goal links on partial edits and validates merged dates", async () => {
    const goal = await create("goal");
    const task = await create("task", {
      parentId: goal.id,
      goalId: goal.id,
      startDate: "2026-09-07",
      targetDate: "2026-09-09",
    });
    const changed = await data(
      await invoke(
        routes.entry.PATCH,
        "PATCH",
        { title: "Renamed task" },
        primaryJar,
        String(task.id),
      ),
    );
    expect(changed).toMatchObject({
      parentId: goal.id,
      goalId: goal.id,
      startDate: "2026-09-07",
      targetDate: "2026-09-09",
    });
    expect(
      (
        await invoke(
          routes.entry.PATCH,
          "PATCH",
          { targetDate: "2026-09-06" },
          primaryJar,
          String(task.id),
        )
      ).status,
    ).toBe(400);
    expect(
      (await invoke(routes.entry.PATCH, "PATCH", { kind: "note" }, primaryJar, String(task.id)))
        .status,
    ).toBe(400);
  });

  it("prevents hierarchy cycles under simultaneous edits", async () => {
    const first = await create("goal");
    const second = await create("goal");
    const responses = await Promise.all([
      invoke(routes.entry.PATCH, "PATCH", { parentId: second.id }, primaryJar, String(first.id)),
      invoke(routes.entry.PATCH, "PATCH", { parentId: first.id }, primaryJar, String(second.id)),
    ]);
    expect(responses.map((response) => response.status).sort()).toEqual([200, 400]);
    const rows = await db.entry.findMany({
      where: { id: { in: [String(first.id), String(second.id)] }, userId: primaryId },
    });
    expect(rows.filter((row) => row.parentId).length).toBe(1);
  });

  it("creates one recurring successor under retries, concurrent completion and reopening", async () => {
    const task = await create("task", {
      targetDate: "2026-01-31",
      details: { recurrence: "monthly" },
    });
    const id = String(task.id);
    const responses = await Promise.all(
      Array.from({ length: 3 }, () =>
        invoke(routes.entry.PATCH, "PATCH", { status: "done" }, primaryJar, id),
      ),
    );
    expect(responses.map((response) => response.status)).toEqual([200, 200, 200]);
    await data(await invoke(routes.entry.PATCH, "PATCH", { status: "active" }, primaryJar, id));
    await data(await invoke(routes.entry.PATCH, "PATCH", { status: "done" }, primaryJar, id));
    const successors = await db.entry.findMany({
      where: { recurrenceSourceId: id, userId: primaryId },
    });
    expect(successors).toHaveLength(1);
    expect(successors[0]).toMatchObject({
      status: "planned",
      progress: 0,
      targetDate: "2026-02-28",
    });
  });

  it("upserts habit check-ins idempotently and rejects invalid dates and owners", async () => {
    const today = todayInTimezone();
    const habit = await create("habit", {
      startDate: today,
      details: { frequency: "daily", target: 2 },
    });
    const entryId = String(habit.id);
    const responses = await Promise.all(
      Array.from({ length: 3 }, () =>
        invoke(routes.habits.POST, "POST", { entryId, date: today, count: 2 }),
      ),
    );
    expect(responses.map((response) => response.status)).toEqual([200, 200, 200]);
    expect(await db.habitLog.count({ where: { entryId } })).toBe(1);
    expect(
      (await invoke(routes.habits.POST, "POST", { entryId, date: addDays(today, 1), count: 1 }))
        .status,
    ).toBe(400);
    expect(
      (await invoke(routes.habits.POST, "POST", { entryId, date: addDays(today, -1), count: 1 }))
        .status,
    ).toBe(400);
    expect(
      (await invoke(routes.habits.POST, "POST", { entryId, date: today, count: 1 }, otherJar))
        .status,
    ).toBe(404);
    await data(await invoke(routes.habits.POST, "POST", { entryId, date: today, count: 0 }));
    expect(await db.habitLog.count({ where: { entryId } })).toBe(0);
  });

  it("records study time only for owned learning items and deletes owned sessions", async () => {
    const learning = await create("learning", {
      details: { topic: "DevOps", resourceLinks: ["https://kubernetes.io/docs/"] },
    });
    const date = todayInTimezone();
    const session = await data(
      await invoke(routes.study.POST, "POST", {
        entryId: learning.id,
        date,
        minutes: 45,
        notes: "Practiced deployments",
      }),
    );
    expect(
      (
        await invoke(
          routes.study.POST,
          "POST",
          { entryId: learning.id, date, minutes: 45 },
          otherJar,
        )
      ).status,
    ).toBe(404);
    expect(
      (
        await invoke(routes.study.POST, "POST", {
          entryId: learning.id,
          date: addDays(date, 1),
          minutes: 45,
        })
      ).status,
    ).toBe(400);
    expect(
      (await invoke(routes.studyItem.DELETE, "DELETE", undefined, otherJar, String(session.id)))
        .status,
    ).toBe(404);
    expect(
      (await invoke(routes.studyItem.DELETE, "DELETE", undefined, primaryJar, String(session.id)))
        .status,
    ).toBe(200);
  });

  it("preserves financial currency, notes and savings balance on partial updates", async () => {
    const transaction = await data(
      await invoke(routes.transactions.POST, "POST", {
        title: "Book",
        type: "expense",
        amount: 29.99,
        category: "Learning",
        date: "2026-09-07",
        currency: "USD",
        notes: "Reference",
      }),
    );
    const changed = await data(
      await invoke(
        routes.transaction.PATCH,
        "PATCH",
        { title: "Cloud book" },
        primaryJar,
        String(transaction.id),
      ),
    );
    expect(changed).toMatchObject({ currency: "USD", notes: "Reference", amount: 29.99 });
    expect(
      (
        await invoke(
          routes.transaction.PATCH,
          "PATCH",
          { amount: 1 },
          otherJar,
          String(transaction.id),
        )
      ).status,
    ).toBe(404);
    const saving = await data(
      await invoke(routes.savings.POST, "POST", {
        title: "Laptop",
        targetAmount: 2000,
        savedAmount: 450.5,
        currency: "USD",
        targetDate: "2027-01-01",
      }),
    );
    expect(
      await data(
        await invoke(
          routes.saving.PATCH,
          "PATCH",
          { title: "Work laptop" },
          primaryJar,
          String(saving.id),
        ),
      ),
    ).toMatchObject({ savedAmount: 450.5, currency: "USD", targetDate: "2027-01-01" });
    expect(
      (await invoke(routes.saving.DELETE, "DELETE", undefined, otherJar, String(saving.id))).status,
    ).toBe(404);
    const budgetInput = { category: "Learning", month: "2026-09", amount: 100, currency: "USD" };
    const budget = await data(await invoke(routes.budgets.POST, "POST", budgetInput));
    expect((await invoke(routes.budgets.POST, "POST", budgetInput)).status).toBe(409);
    expect(
      await data(
        await invoke(routes.budget.PATCH, "PATCH", { amount: 150 }, primaryJar, String(budget.id)),
      ),
    ).toMatchObject({ currency: "USD", amount: 150 });
  });

  it("upserts a daily plan and cascades only its owner's deleted entry logs", async () => {
    const input = {
      date: todayInTimezone(),
      priorities: ["Ship a small change"],
      reflection: "Practiced a new skill",
    };
    const first = await data(await invoke(routes.planner.PUT, "PUT", input));
    const second = await data(
      await invoke(routes.planner.PUT, "PUT", { ...input, notes: "Take a break" }),
    );
    expect(second.id).toBe(first.id);
    const habit = await create("habit");
    await data(
      await invoke(routes.habits.POST, "POST", { entryId: habit.id, date: input.date, count: 1 }),
    );
    await data(
      await invoke(routes.entry.DELETE, "DELETE", undefined, primaryJar, String(habit.id)),
    );
    expect(await db.habitLog.count({ where: { entryId: String(habit.id) } })).toBe(0);
    expect(await db.user.count({ where: { id: otherId } })).toBe(1);
  });

  it("changes initial passwords, revokes old sessions and refuses stale password sessions", async () => {
    const oldJar = newJar();
    for (const [key, value] of initialJar.values) oldJar.values.set(key, value);
    const newPassword = `Updated ${randomBytes(24).toString("hex")}!`;
    const oldHash = (await db.user.findUniqueOrThrow({ where: { id: initialId } })).passwordHash;
    expect(
      (
        await invoke(
          routes.password.POST,
          "POST",
          { currentPassword: "incorrect", newPassword },
          initialJar,
        )
      ).status,
    ).toBe(400);
    expect(
      (
        await invoke(
          routes.password.POST,
          "POST",
          { currentPassword: testPassword, newPassword },
          initialJar,
        )
      ).status,
    ).toBe(200);
    expect((await invoke(routes.workspace.GET, "GET", undefined, oldJar)).status).toBe(401);
    expect((await invoke(routes.workspace.GET, "GET", undefined, initialJar)).status).toBe(200);
    expect((await db.user.findUniqueOrThrow({ where: { id: initialId } })).mustChangePassword).toBe(
      false,
    );
    const { createSession } = await import("@/lib/auth");
    await expect(
      cookieStorage.run(newJar(), () => createSession(initialId, oldHash)),
    ).rejects.toMatchObject({ status: 401 });
    expect(
      (
        await invoke(
          routes.login.POST,
          "POST",
          { email: initialEmail, password: testPassword },
          newJar(),
        )
      ).status,
    ).toBe(401);
    expect((await invoke(routes.logout.POST, "POST", {}, initialJar)).status).toBe(200);
    expect((await invoke(routes.workspace.GET, "GET", undefined, initialJar)).status).toBe(401);
  });

  it("rejects expired sessions and throttles ten failed account sign-ins", async () => {
    const expiredJar = newJar();
    await data(
      await invoke(
        routes.login.POST,
        "POST",
        { email: primaryEmail, password: testPassword },
        expiredJar,
      ),
    );
    const token = expiredJar.values.get("life_planning_session")!;
    await db.session.update({
      where: { tokenHash: hashToken(token) },
      data: { expiresAt: new Date(Date.now() - 1000) },
    });
    expect((await invoke(routes.workspace.GET, "GET", undefined, expiredJar)).status).toBe(401);
    for (let attempt = 0; attempt < 10; attempt++)
      expect(
        (
          await invoke(
            routes.login.POST,
            "POST",
            { email: throttleEmail, password: "wrong" },
            newJar(),
          )
        ).status,
      ).toBe(401);
    expect(
      (
        await invoke(
          routes.login.POST,
          "POST",
          { email: throttleEmail, password: testPassword },
          newJar(),
        )
      ).status,
    ).toBe(429);
    expect(
      await db.loginAudit.count({
        where: { emailHash: hashToken(throttleEmail), successful: false },
      }),
    ).toBe(10);
  }, 60000);
});
